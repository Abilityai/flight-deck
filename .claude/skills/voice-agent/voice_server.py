def voice_session_ids():
    """Session ids this voice agent has produced, read from its own logs: (real sessions, test-run sessions)."""
    ids, tests = set(), set()
    for log in DATA_DIR.glob("*.jsonl"):
        try:
            text = log.read_text(errors="ignore")
        except OSError:
            continue
        # Test runs use --strict-mcp: flagged since 2026-11-02, and before that recognisable by an init with no MCP tools.
        is_test = '"test": true' in text or ('"event": "init"' in text and '"mcp__' not in text)
        (tests if is_test else ids).update(SESSION_ID.findall(text))
    return ids - tests, tests


def _prompt_text(content):
    if isinstance(content, list):
        content = " ".join(c.get("text", "") for c in content if isinstance(c, dict) and c.get("type") == "text")
    text = " ".join(str(content or "").split())
    return "" if not text or text.startswith("<") else text


def list_sessions(limit=25):
    """Recent Claude Code sessions in this project, newest first, for the resume picker."""
    files = sorted(TRANSCRIPTS.glob("*.jsonl"), key=lambda f: f.stat().st_mtime, reverse=True)
    voice, tests = voice_session_ids()
    out = []
    for f in files:
        if len(out) >= limit:
            break
        sid = f.stem
        if not SESSION_ID.fullmatch(sid) or sid in tests:
            continue
        title, last, turns = "", "", 0
        try:
            with open(f, errors="ignore") as fh:
                for line in fh:
                    if '"ai-title"' in line or '"custom-title"' in line:
                        try:
                            d = json.loads(line)
                            title = d.get("customTitle") or d.get("aiTitle") or title
                        except ValueError:
                            pass
                    elif line.startswith('{"parentUuid"') and '"type":"user"' in line and '"isMeta"' not in line:
                        try:
                            d = json.loads(line)
                        except ValueError:
                            continue
                        if d.get("isSidechain"):
                            continue
                        text = _prompt_text((d.get("message") or {}).get("content"))
                        if text:
                            last, turns = text, turns + 1
        except OSError:
            continue
        if not turns:
            continue
        out.append({"id": sid, "title": (title or last)[:90], "last": last[:140], "turns": turns,
                    "voice": sid in voice, "mtime": int(f.stat().st_mtime)})
    return out


def spoken_intent(description):
    """Claude's plain-words purpose for a command, shaped to follow "I need your approval to". The exact command stays on screen."""
    text = " ".join(str(description or "").split()).rstrip(".")[:140]
    if not text:
        return ""
    return text if text[1:2].isupper() else text[0].lower() + text[1:]


