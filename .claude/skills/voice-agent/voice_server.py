def looks_unfinished(text):
    """A pause mid-thought reaches transcription as a fragment: no closing punctuation, or a trailing filler or connector."""
    t = (text or "").strip()
    return not re.search(r"[.?!\u2026]$", t) or bool(UNFINISHED_END.search(t))


