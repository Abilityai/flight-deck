def inside_project(path):
    if not path:
        return True
    p = Path(path if os.path.isabs(path) else ROOT / path).resolve()
    return p == ROOT or ROOT in p.parents


def decide(tool, args):
    """Return 'allow', 'voice' (spoken yes works) or 'click' (on-screen approval only)."""
    args = args or {}
    if tool in PATH_TOOLS or tool == "Read":
        path = args.get("file_path") or args.get("path") or ""
        if SENSITIVE_PATH.search(path) or not inside_project(path):
            return "click"
        return "allow"
    if tool in SAFE_TOOLS:
        return "allow"
    if tool == "Bash":
        cmd = (args.get("command") or "").strip()
        if (not BASH_METACHAR.search(cmd) and BASH_READ.match(cmd) and not SENSITIVE_PATH.search(cmd)
                and ".." not in cmd and not re.search(r"\s(/|~)", cmd)):
            return "allow"
        risky = BASH_CLICK.search(cmd) or BASH_METACHAR.search(cmd) or BASH_CLICK_ARGS.search(cmd)
        return "click" if risky else "voice"
    if tool in ("Write", "Edit", "NotebookEdit", "MultiEdit"):
        path = args.get("file_path") or args.get("notebook_path") or ""
        return "voice" if inside_project(path) and not SENSITIVE_PATH.search(path) else "click"
    if tool == "Skill":
        return "click" if SKILL_CLICK.search(args.get("skill") or args.get("command") or "") else "voice"
    if tool.startswith("mcp__"):
        parts = tool.split("__", 2)
        server, name = parts[1], parts[2] if len(parts) > 2 else ""
        if MCP_CLICK_SERVER.search(server) or MCP_SECRET.search(name) or MCP_CLICK.search(name):
            return "click"
        return "allow" if MCP_READ.match(name) else "voice"
    return "click"


