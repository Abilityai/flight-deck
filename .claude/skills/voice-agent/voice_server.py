def open_in_iterm(session_id):
    """Continue a Claude Code session in a new iTerm tab, in this agent's folder. Returns (ok, error)."""
    cmd = f"cd {shlex.quote(str(ROOT))} && claude --dangerously-skip-permissions --resume {session_id}"
    try:   # the command travels as an argument, never inside the script text
        r = subprocess.run(["osascript", "-", cmd], input=ITERM_SCRIPT, text=True, capture_output=True, timeout=20)
    except (OSError, subprocess.TimeoutExpired) as e:
        return False, str(e)
    return r.returncode == 0, (r.stderr or "").strip()[:300]


