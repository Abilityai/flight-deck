def ambient():
    """Weather and sun times for the page's ambient tint. Only a place NAME leaves this Mac, to open-meteo.com."""
    with AMBIENT["lock"]:
        if AMBIENT["data"] is not None and time.time() - AMBIENT["at"] < 900:
            return AMBIENT["data"]
        data = {"ok": False}
        try:
            place = ambient_place()
            q = urllib.parse.urlencode({"name": place, "count": 1})
            with urllib.request.urlopen(f"https://geocoding-api.open-meteo.com/v1/search?{q}", timeout=6) as r:
                g = json.load(r)["results"][0]
            q = urllib.parse.urlencode({"latitude": round(g["latitude"], 2), "longitude": round(g["longitude"], 2),
                                        "current": "temperature_2m,weather_code,cloud_cover,is_day,precipitation",
                                        "daily": "sunrise,sunset", "timezone": "auto", "forecast_days": 1})
            with urllib.request.urlopen(f"https://api.open-meteo.com/v1/forecast?{q}", timeout=6) as r:
                w = json.load(r)
            cur, day = w["current"], w["daily"]
            data = {"ok": True, "place": g.get("name") or place, "temp": cur.get("temperature_2m"),
                    "code": cur.get("weather_code"), "cloud": cur.get("cloud_cover"), "is_day": cur.get("is_day"),
                    "sunrise": day["sunrise"][0][-5:], "sunset": day["sunset"][0][-5:]}
        except Exception as e:   # no network, unknown place, changed API: the page falls back to time and date only
            data = {"ok": False, "error": type(e).__name__}
        AMBIENT["data"], AMBIENT["at"] = data, time.time()
        return data


