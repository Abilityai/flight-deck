def gemini_key():
    key = os.environ.get("GEMINI_API_KEY") or os.environ.get("GOOGLE_API_KEY")
    if key:
        return key
    try:
        servers = json.loads((ROOT / ".mcp.json").read_text()).get("mcpServers", {})
        for cfg in servers.values():
            if cfg.get("env", {}).get("GEMINI_API_KEY", "").startswith("AIza"):
                return cfg["env"]["GEMINI_API_KEY"]
    except (OSError, ValueError):
        pass
    return None


def gemini_post(model, method, body, timeout):
    req = urllib.request.Request(f"{GEMINI}{model}:{method}", json.dumps(body).encode(),
                                 {"Content-Type": "application/json", "x-goog-api-key": gemini_key() or ""})
    return urllib.request.urlopen(req, timeout=timeout)


def pad_silence(wav, seconds=0.7):
    """The Gemini model repeatably drops trailing words from audio that ends without silence."""
    with wave.open(io.BytesIO(wav)) as r:
        params, frames = r.getparams(), r.readframes(r.getnframes())
    pad = b"\0" * (int(params.framerate * seconds) * params.sampwidth * params.nchannels)
    out = io.BytesIO()
    with wave.open(out, "wb") as w:
        w.setparams(params)
        w.writeframes(pad + frames + pad)
    return out.getvalue()


def transcribe_gemini(wav):
    wav = pad_silence(wav)
    body = {"contents": [{"parts": [
        {"text": "Transcribe this audio verbatim, in the language spoken. Output only the transcript."},
        {"inlineData": {"mimeType": "audio/wav", "data": base64.b64encode(wav).decode()}}]}]}
    data = json.load(gemini_post(STT_MODEL, "generateContent", body, 20))
    parts = (data.get("candidates") or [{}])[0].get("content", {}).get("parts", [])
    text = " ".join(p.get("audioTranscription", {}).get("text") or p.get("text", "") for p in parts)
    return text.strip()


def transcribe_whisper(wav):
    with tempfile.NamedTemporaryFile(suffix=".wav") as f:
        f.write(wav)
        f.flush()
        r = subprocess.run(["whisper-cli", "-m", str(WHISPER_MODEL), "-nt", "-l", "auto", "-f", f.name],
                           capture_output=True, text=True, timeout=60)
    return re.sub(r"\[[^\]]*\]|\([^)]*\)", "", r.stdout).strip()


def tts_stream(text, voice):
    """Yield (rate, little-endian PCM). Raises if no model produced audio."""
    last = None
    for model in TTS_MODELS:
        got = False
        try:
            resp = gemini_post(model, "streamGenerateContent?alt=sse", {
                "contents": [{"parts": [{"text": text}]}],
                "generationConfig": {"responseModalities": ["AUDIO"], "speechConfig": {
                    "voiceConfig": {"prebuiltVoiceConfig": {"voiceName": voice}}}}}, 30)
            spill = b""
            for line in resp:
                if not line.startswith(b"data:"):
                    continue
                ev = json.loads(line[5:])
                for part in (ev.get("candidates") or [{}])[0].get("content", {}).get("parts", []):
                    inline = part.get("inlineData")
                    if not inline:
                        continue
                    m = re.search(r"rate=(\d+)", inline.get("mimeType", ""))
                    pcm = spill + base64.b64decode(inline["data"])
                    even = len(pcm) & ~1
                    spill = pcm[even:]
                    if even:
                        got = True
                        yield int(m.group(1)) if m else 24000, pcm[:even]
            if got:
                return
            last = RuntimeError(f"{model} returned no audio")
        except (urllib.error.URLError, OSError, ValueError) as e:
            if got:
                raise
            last = e
    raise last or RuntimeError("no TTS model configured")


def say_fallback(text):
    with tempfile.TemporaryDirectory() as d:
        aiff, raw = os.path.join(d, "s.aiff"), os.path.join(d, "s.raw")
        subprocess.run(["say", "-o", aiff, text], check=True, timeout=30)
        subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-i", aiff, "-f", "s16le", "-ar", "24000",
                        "-ac", "1", raw], check=True, timeout=30)
        return Path(raw).read_bytes()


