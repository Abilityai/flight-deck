def classify_reply(text):
    """Only an exact short reply counts, so echoed prompts and asides can never approve anything."""
    t = re.sub(r"[^a-z ]", "", text.lower().replace("'", "")).strip()
    t = re.sub(r"\s+", " ", t)
    return "yes" if t in YES else "no" if t in NO else "other"


# ───────────────────────────── text to speech chunks ─────────────────────────
ABBREV = re.compile(r"(\b(e\.g|i\.e|vs|mr|mrs|ms|dr|etc|no|st|inc|ltd)\.|\b\d+\.)$", re.I)
SENTENCE = re.compile(r".+?(?:[.!?…]+[\"')\]]*(?=\s)|\n+)", re.S)


def clean_for_speech(text):
    t = re.sub(r"\[([^\]]+)\]\((?:[^)]+)\)", r"\1", text)
    t = re.sub(r"https?://\S+", "", t)
    t = re.sub(r"[*_`#|>~]+", " ", t)
    t = re.sub(r"(^|\n)\s*(-|\d+\.)\s+", r"\1", t)
    t = t.replace("—", ", ").replace("–", ", ")
    t = re.sub(r"\s+", " ", t).strip()
    return t if re.search(r"\w", t) else ""


class SpeechChunker:
    """Turns streaming model text into speakable sentences and on-screen blocks."""
    BLOCKS = {"<screen>": "</screen>", "```": "```", "<face>": "</face>"}
    FACE_MAX = 40   # a <face> tag holds one word; an unclosed one must never swallow the reply

    def __init__(self):
        self.buf, self.close, self.block, self.opener = "", None, "", None

    def feed(self, delta):
        self.buf += delta
        return self._drain(False)

    def flush(self):
        out = self._drain(True)
        self.close, self.block, self.buf = None, "", ""
        return out

    def _block_text(self, text):
        """A code block keeps its fences so the page renders it as code; <screen> content is markdown as written."""
        if self.opener == "```":
            return "```" + text.rstrip() + "\n```"
        return text.strip()

    def _sentences(self, text, final):
        out, pos = [], 0
        for m in SENTENCE.finditer(text):
            s = text[pos:m.end()]
            if len(s.strip()) < 12 or ABBREV.search(s.strip()):
                continue
            out.append(s)
            pos = m.end()
        rest = text[pos:]
        if not final and len(rest) > 200 and ", " in rest[60:]:   # long clause: do not leave the listener waiting
            cut = rest.rfind(", ") + 1
            out.append(rest[:cut])
            rest = rest[cut:]
        if final and rest.strip():
            out.append(rest)
            rest = ""
        return out, rest

    def _drain(self, final):
        out = []
        while True:
            if self.close:
                i = self.buf.find(self.close)
                if self.opener == "<face>":
                    if 0 <= i <= self.FACE_MAX:
                        out.append(("face", self.buf[:i].strip().lower()))
                        self.buf = self.buf[i + len(self.close):].lstrip(" ")
                        self.close = None
                        continue
                    if i >= 0 or final or len(self.buf) > self.FACE_MAX:
                        self.close = None   # malformed: drop the opener, treat what follows as ordinary text
                        continue
                    return out
                if i < 0:
                    if final:
                        out.append(("screen", self._block_text(self.buf)))
                        self.buf = ""
                    return out
                out.append(("screen", self._block_text(self.buf[:i])))
                self.buf = self.buf[i + len(self.close):]
                self.close = None
                continue
            hits = [(self.buf.find(o), o) for o in self.BLOCKS if o in self.buf]
            if hits:
                i, opener = min(hits)
                sents, rest = self._sentences(self.buf[:i], True)
                out += [("say", s) for s in sents]
                self.buf = self.buf[i + len(opener):]
                self.close = self.BLOCKS[opener]
                self.opener = opener
                continue
            hold = 0
            if not final:
                for o in self.BLOCKS:
                    for n in range(len(o) - 1, 0, -1):
                        if self.buf.endswith(o[:n]):
                            hold = max(hold, n)
                            break
            scan = self.buf[:-hold] if hold else self.buf
            tail = self.buf[-hold:] if hold else ""
            sents, rest = self._sentences(scan, final)
            out += [("say", s) for s in sents]
            self.buf = rest + tail
            return out


