        self.held_timer = None
        self.user_speaking = False
        self.still_said = False
        self.turn_grants = set()
        self.first_audio_logged = False
        self.spoken_words = 0
        self.overflow = []
        self.overflow_said = False
        self.total_cost = 0.0
        self.closing = False
